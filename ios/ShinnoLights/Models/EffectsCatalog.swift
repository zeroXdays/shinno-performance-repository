    /// G37 LEDDMX kits use the LED LAMP table; Q50 ELK/MELK keep Lotus Lantern ids.
    static func effects(for car: CarKind) -> [LedEffect] {
        car == .g37 ? dmxAll : all
    }

    static func named(_ id: Int?, car: CarKind = .q50) -> String? {
        guard let id else { return nil }
        return effects(for: car).first { $0.id == id }?.name
    }

    static func inGroup(_ group: EffectGroup, car: CarKind = .q50) -> [LedEffect] {
        effects(for: car).filter { $0.group == group }
    }
